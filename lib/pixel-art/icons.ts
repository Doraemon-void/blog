export type PixelIconName = keyof typeof ICONS;

export const iconNames = Object.keys(ICONS) as PixelIconName[];

/* Validate every grid once, at import time. */
const GRID = 16;
for (const [name, rows] of Object.entries(ICONS)) {
  if (rows.length !== GRID) {
    throw new Error(
      `[pixel-art/icons] "${name}" has ${rows.length} rows, expected ${GRID}.`,
    );
  }
  rows.forEach((row, index) => {
    if (row.length !== GRID) {
      throw new Error(
        `[pixel-art/icons] "${name}" row ${index} is ${row.length} cells, expected ${GRID}.`,
      );
    }
  });
}

export function getIconRows(name: PixelIconName): readonly string[] {
  return ICONS[name];
}

export { ICONS };
