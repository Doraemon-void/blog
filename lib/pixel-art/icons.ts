/**
 * Hand-drawn pixel icons, 16×16 on a single grid (spec §57).
 *
 * Why hand-drawn instead of emoji or an icon font: spec §57 rules out emoji as
 * UI icons, and every off-the-shelf icon set is drawn for smooth vector
 * rendering — its curves and 1px strokes turn to mush on a pixel grid. These
 * are authored cell by cell so they stay legible at 16px.
 *
 * Legend (see lib/pixel-art/palette.ts):
 *   `x` = currentColor, so an icon follows the text colour and adapts to dark
 *         mode without a second asset.
 *   `m` = mint, `M` = mint-dark, `s` = sky, `y` = yellow, `c` = coral
 *         — reserved for the few icons that carry an accent.
 *   `.` = transparent
 *
 * Rows are validated below. A miscounted row is the single most likely mistake
 * when editing this file, and the failure it causes in an SVG is silent (art
 * shifts, nothing errors), so it is caught at import time instead.
 */

